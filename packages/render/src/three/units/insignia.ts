/**
 * GH-1096 S1: the Roaring Lion insignia, PAINTED on a KDF vehicle's hull (spec
 * `docs/superpowers/specs/2026-11-12-gh1096-lion-insignia-design.md`, sections 4 and 7).
 *
 * **What it is.** One shared 256 x 256 two-channel signed-distance texture (`assets/textures/insignia/roaring_lion_sdf.png`,
 * baked by `tools/insignia/bake_sdf.py` from the hand-drawn `art/src/insignia/roaring_lion.svg`), sampled in the fragment shader
 * on a planar frame in the vehicle's OWN mesh-local space: a flank pair, mirrored about the centreline. It rides the L3 team-mark
 * hook (`team-mask.ts`): one `onBeforeCompile`, one program key (`rl-unit-mark-3`), one `carryTeamMark` at every clone site. So it
 * is paint on the hull, +0 draw calls, +0 bytes in any GLB, turns with a turret, and a wreck (no hook) takes none.
 *
 * **Where.** `insignia-frames.ts`, GENERATED by `tools/vehicles/insignia.py` (never hand-edited), one frame per unit TYPE id.
 *
 * **The maths** (`insigniaOps`, written once against `Ops<T>`; the legacy GLSL below and the node twin run the same body):
 *
 *     e       = ((p.x - cx) / D + 0.5, (p.y - cy) / D + 0.5)          emblem coordinate, 0..1 across the disc
 *     inside  = cov(|p.z|, zlo, zhi) * soft(min_n, |n.z|) * cov(e.x, 0, 1) * cov(e.y, 0, 1)
 *     px      = 1 / max(fwidth(e.x), fwidth(e.y)) / pixelRatio       the SHORTER screen axis, CSS px
 *     sil     = edge(sdf.r)   cut = edge(sdf.g)                     anti-aliased over about one screen pixel
 *     roundel = smoothstep(5, 7.5, px)   detail = smoothstep(15, 20, px)
 *     mask    = strength * inside * roundel * sil * (1 - detail * cut)
 *     diffuse = mix(diffuse, min(colour * mix(1, luma(diffuse) / luma_ref, 0.3), 1), mask)
 *
 * Two deliberate differences from the spec's sketch, each measured:
 *  - **The normal test is `|n.z|`, the team band's, not `sign(p.z) * n.z`.** The Lavi's -z flank is mirrored geometry on a
 *    double-sided material: its vertex AND winding normals point +z (inward), mean n.z 0.984 there, so the signed test reads -0.98
 *    and would paint one flank only. The slab `[zlo, zhi]` is what keeps the far side and the interior out, as on the team band.
 *  - **The detail band is 15-20 px** (the lead's ruling of 12 Nov on GH-1096, after the S0 read: the face does not read at 11 px).
 *
 * **LOD.** The measure is the emblem's own screen size per fragment, so the battlefield, the garage turntable and a flank seen
 * edge-on all follow one rule with no special case. The bands are SHARED uniforms (`setInsigniaBands`), tunable with no re-bake.
 *
 * **The texture.** It is data: `NoColorSpace`, no premultiply, mips on, clamped. Each OWNER (a `ThreeRenderer`, a garage view)
 * holds one `InsigniaShared`: until the PNG lands a 1 x 1 placeholder (R = 0, "outside") is bound, and the load swaps the uniform's
 * `.value`, so nothing recompiles. A failed load logs a `console.error` naming the file and keeps the placeholder: the units draw
 * exactly as before, never a black box, never a throw.
 *
 * **The colour** is the palette key `limestone.1`, fixed for the faction, never a team slot (a KDF seat can be the hostile one in a
 * versus room), resolved through `paletteHex` and handed to the shader LINEAR.
 *
 * Presentation only. Nothing here is read by the sim.
 */
import * as THREE from 'three';
import { hexToLinear } from '../terrain/shared';
import { paletteHex } from '../palette-hex';
import type { Ops } from '../fog-ops';

/** The lead's ruling for the team mark (2 Nov, GH-943), reused for the insignia (GH-1096 decision 7). */
export const INSIGNIA_STRENGTH = 0.85;
/** GH-1096 decision 5: a warm sand-white stencil, fixed for the faction. A palette KEY, never a hex. */
export const INSIGNIA_COLOR_KEY = 'limestone.1';
/**
 * The LOD bands in CSS px on the emblem's shorter screen axis: the roundel fades in over [0, 1], the lion's face over [2, 3].
 * Roundel 5-7.5 (decision 13); detail 15-20 (the lead's ruling of 12 Nov, superseding decision 13's 11-15).
 */
export const INSIGNIA_BANDS_PX: readonly [number, number, number, number] = [5, 7.5, 15, 20];
/** How much of the bake's grime the paint keeps (the team mark's ruling). */
export const INSIGNIA_GRIME = 0.3;
/** Half the soft band the normal test eases over. */
export const INSIGNIA_NORMAL_SOFT = 0.04;
/** The smallest rate any coverage, edge or size divides by. */
export const INSIGNIA_MIN_RATE = 1e-5;
/**
 * The texture's layout (`bake_sdf.py`): 256 texels, the 200-unit viewBox spanning texels 8..248, so the emblem disc's 0..1 maps
 * to `ST_OFFSET + ST_SCALE * e` (8/256 and 240/256).
 */
export const INSIGNIA_ST_OFFSET = 8 / 256;
export const INSIGNIA_ST_SCALE = 240 / 256;
/** The distance field's edge: `128 + 16 * d` stored in 8 bits, read back as `128 / 255`. */
export const INSIGNIA_SDF_EDGE = 128 / 255;
/** Rec. 709 luminance of a LINEAR colour, as the team mark. */
export const INSIGNIA_LUMA_WEIGHTS = [0.2126, 0.7152, 0.0722] as const;

/** One vehicle type's emblem pair (`insignia-frames.ts`, generated): metres, mesh-local (X forward, Y up, Z lateral). */
export interface InsigniaFrame {
  /** The disc's centre on the +z flank; the pair sits at z = +cz and -cz. */
  readonly centre: readonly [number, number, number];
  /** The roundel's diameter. */
  readonly d: number;
  /** The `|z|` range a fragment must be in: the host flank and any outer kit plate, nothing behind. */
  readonly slab: readonly [number, number];
  /** Flank faces only: `|n.z|` above this, eased by `INSIGNIA_NORMAL_SOFT`. */
  readonly min_n: number;
  /** Mean LINEAR luminance of the bake under the disc (the grime normaliser). */
  readonly luma: number;
  /** sha256 of the host hull POSITION accessors this frame was measured on (`validate:meshes` re-hashes them). */
  readonly host_sha256: string;
}

type V2<T> = readonly [T, T];
type V3<T> = readonly [T, T, T];
type V4<T> = readonly [T, T, T, T];

/** The emblem coordinate `e` and the texture coordinate `st` of an object-space position. `frame` is `uInsFrame`: cx, cy, D, min_n. */
export function insigniaCoordOps<T>(o: Ops<T>, p: V3<T>, frame: V4<T>): { e: [T, T]; st: [T, T] } {
  const half = o.lit(0.5);
  const ex = o.add(o.div(o.sub(p[0], frame[0]), frame[2]), half);
  const ey = o.add(o.div(o.sub(p[1], frame[1]), frame[2]), half);
  const st = (v: T): T => o.add(o.lit(INSIGNIA_ST_OFFSET), o.mul(o.lit(INSIGNIA_ST_SCALE), v));
  return { e: [ex, ey], st: [st(ex), st(ey)] };
}

/**
 * What `insigniaOps` reads. Every screen-space rate is computed by the CALLER (a derivative is graph-only, and a texture fetch is
 * not an `Ops<T>` operation): the sample and the rates arrive as inputs, computed outside any branch.
 */
export interface InsigniaInput<T> {
  /** `vMarkPos`, `vMarkNrm`: the OBJECT-space position and the (unnormalised) object-space normal. */
  readonly p: V3<T>;
  readonly n: V3<T>;
  /** `insigniaCoordOps(...).e`, and `fwidth` of each component. */
  readonly e: V2<T>;
  readonly rateE: V2<T>;
  /** `fwidth(abs(p.z))`. */
  readonly rateZ: T;
  /** The distance field at `st`: R (silhouette) and G (cut-outs), 0..1, and `fwidth` of each. */
  readonly sample: V2<T>;
  readonly rateS: V2<T>;
  /** `uInsFrame` (cx, cy, D, min_n), `uInsSlab` (zlo, zhi), `uInsBands` (the four px thresholds). */
  readonly frame: V4<T>;
  readonly slab: V2<T>;
  readonly bands: V4<T>;
  readonly pixelRatio: T;
  readonly strength: T;
  readonly luma: T;
  /** The paint colour, LINEAR. */
  readonly color: V3<T>;
  /** The diffuse colour before the insignia (after the map, the tread and the team mark). */
  readonly diffuse: V3<T>;
}

/** `INSIGNIA_FRAGMENT`, written once against `Ops<T>`. Returns the mask, the emblem's screen size and the colour after it. */
export function insigniaOps<T>(o: Ops<T>, i: InsigniaInput<T>): { mask: T; px: T; rgb: [T, T, T] } {
  const one = o.lit(1);
  const half = o.lit(0.5);
  const zero = o.lit(0);
  const minRate = o.lit(INSIGNIA_MIN_RATE);
  const cov = (v: T, lo: T, hi: T, rate: T): T => {
    const w = o.max(rate, minRate);
    return o.mul(o.clamp01(o.add(o.div(o.sub(v, lo), w), half)), o.clamp01(o.add(o.div(o.sub(hi, v), w), half)));
  };
  const edge = (s: T, rate: T): T => o.clamp01(o.add(o.div(o.sub(s, o.lit(INSIGNIA_SDF_EDGE)), o.max(rate, minRate)), half));
  const len = o.sqrt(o.add(o.add(o.mul(i.n[0], i.n[0]), o.mul(i.n[1], i.n[1])), o.mul(i.n[2], i.n[2])));
  const nz = o.abs(o.div(i.n[2], len));
  const soft = o.smoothstep(o.sub(i.frame[3], o.lit(INSIGNIA_NORMAL_SOFT)), o.add(i.frame[3], o.lit(INSIGNIA_NORMAL_SOFT)), nz);
  const inside = o.mul(
    o.mul(o.mul(cov(o.abs(i.p[2]), i.slab[0], i.slab[1], i.rateZ), soft), cov(i.e[0], zero, one, i.rateE[0])),
    cov(i.e[1], zero, one, i.rateE[1])
  );
  const px = o.div(o.div(one, o.max(o.max(i.rateE[0], i.rateE[1]), minRate)), i.pixelRatio);
  const sil = edge(i.sample[0], i.rateS[0]);
  const cut = edge(i.sample[1], i.rateS[1]);
  const roundel = o.smoothstep(i.bands[0], i.bands[1], px);
  const detail = o.smoothstep(i.bands[2], i.bands[3], px);
  const mask = o.mul(o.mul(o.mul(o.mul(i.strength, inside), roundel), sil), o.sub(one, o.mul(detail, cut)));
  const bakeY = o.add(
    o.add(o.mul(i.diffuse[0], o.lit(INSIGNIA_LUMA_WEIGHTS[0])), o.mul(i.diffuse[1], o.lit(INSIGNIA_LUMA_WEIGHTS[1]))),
    o.mul(i.diffuse[2], o.lit(INSIGNIA_LUMA_WEIGHTS[2]))
  );
  const grime = o.mix(one, o.div(bakeY, i.luma), o.lit(INSIGNIA_GRIME));
  const rgb = [0, 1, 2].map((c) => o.mix(i.diffuse[c] as T, o.min(o.mul(i.color[c] as T, grime), one), mask)) as [T, T, T];
  return { mask, px, rgb };
}

