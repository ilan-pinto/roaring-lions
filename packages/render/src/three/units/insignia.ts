// The uniforms.

interface Uniform<T> {
  value: T;
}

/** The strength EVERY insignia material shares: the `insignia` debug layer writes it. Not the team mark's (a separate layer). */
const sharedStrength: Uniform<number> = { value: INSIGNIA_STRENGTH };
/** The LOD bands every insignia material shares. */
const sharedBands: Uniform<THREE.Vector4> = { value: new THREE.Vector4(...INSIGNIA_BANDS_PX) };

/** The shared strength to 0 and back: what the `insignia` debug layer writes (`team-mask.ts`'s `setInsigniaPass`). */
export function setInsigniaStrength(on: boolean): void {
  sharedStrength.value = on ? INSIGNIA_STRENGTH : 0;
}

/** Retune the LOD bands live (the lead's close-up; nothing in the shipped game calls it). */
export function setInsigniaBands(bands: readonly [number, number, number, number]): void {
  sharedBands.value.set(...bands);
}

/**
 * The 1 x 1 "outside" placeholder: R = 0 reads as outside the silhouette, so nothing draws until the real field lands. FILTERED
 * (a `DataTexture` defaults to nearest): the node twin's program is built against whatever is bound first, and WGSL turns a
 * nearest/nearest texture into an unfiltered `textureLoad`, which the late real field would then inherit, mips and all.
 */
function placeholderTexture(): THREE.DataTexture {
  const t = new THREE.DataTexture(new Uint8Array([0, 0, 0, 255]), 1, 1);
  t.colorSpace = THREE.NoColorSpace;
  t.magFilter = THREE.LinearFilter;
  t.minFilter = THREE.LinearFilter;
  t.needsUpdate = true;
  return t;
}

/** The distance field is DATA: no colour conversion, no premultiply, mips on (averaged distances are still a distance field). */
export function prepareInsigniaTexture(tex: THREE.Texture): THREE.Texture {
  tex.colorSpace = THREE.NoColorSpace;
  tex.flipY = true;
  tex.premultiplyAlpha = false;
  tex.wrapS = THREE.ClampToEdgeWrapping;
  tex.wrapT = THREE.ClampToEdgeWrapping;
  tex.generateMipmaps = true;
  tex.minFilter = THREE.LinearMipmapLinearFilter;
  tex.magFilter = THREE.LinearFilter;
  tex.needsUpdate = true;
  return tex;
}

/**
 * What one OWNER (a `ThreeRenderer`, a garage view) shares across every insignia material it mints: the distance field, the paint
 * colour and the pixel ratio. Released by the owner's own disposer.
 */
export class InsigniaShared {
  readonly sdf: Uniform<THREE.Texture>;
  readonly color: Uniform<THREE.Vector3>;
  readonly pixelRatio: Uniform<number>;
  private readonly placeholder: THREE.DataTexture;
  private loaded: THREE.Texture | null = null;
  private disposed = false;

  constructor(colorHex: string = paletteHex(INSIGNIA_COLOR_KEY)) {
    this.placeholder = placeholderTexture();
    this.sdf = { value: this.placeholder };
    this.color = { value: new THREE.Vector3(...hexToLinear(colorHex)) };
    this.pixelRatio = { value: 1 };
  }

  /** The renderer's pixel ratio: `fwidth` is in framebuffer pixels, the bands in CSS px. */
  setPixelRatio(r: number): void {
    this.pixelRatio.value = r > 0 ? r : 1;
  }

  /** Swap the real field in (no recompile: the uniform's value changes). Takes ownership of `tex`. */
  setTexture(tex: THREE.Texture): void {
    if (this.disposed) {
      tex.dispose();
      return;
    }
    this.loaded?.dispose();
    this.loaded = prepareInsigniaTexture(tex);
    this.sdf.value = this.loaded;
  }

  /** Fetch the field. Fail-soft: a failure names the file and keeps the placeholder, so the units draw as they did. */
  load(url: string): Promise<void> {
    return new Promise((resolve) => {
      new THREE.TextureLoader().load(
        url,
        (tex) => {
          this.setTexture(tex);
          resolve();
        },
        undefined,
        () => {
          console.error(`[lions] insignia distance field ${url} failed to load; KDF vehicles draw without the Roaring Lion`);
          resolve();
        }
      );
    });
  }

  get hasTexture(): boolean {
    return this.loaded !== null;
  }

  dispose(): void {
    this.disposed = true;
    this.loaded?.dispose();
    this.loaded = null;
    this.placeholder.dispose();
  }
}

/** One material's insignia hook record: the owner's shared values plus this frame's own. */
export interface InsigniaHook {
  readonly sdf: Uniform<THREE.Texture>;
  readonly color: Uniform<THREE.Vector3>;
  readonly pixelRatio: Uniform<number>;
  readonly strength: Uniform<number>;
  readonly bands: Uniform<THREE.Vector4>;
  readonly luma: Uniform<number>;
  /** cx, cy, D, min_n. */
  readonly frame: Uniform<THREE.Vector4>;
  /** zlo, zhi. */
  readonly slab: Uniform<THREE.Vector2>;
}

export function insigniaHookFor(shared: InsigniaShared, f: InsigniaFrame): InsigniaHook {
  return {
    sdf: shared.sdf,
    color: shared.color,
    pixelRatio: shared.pixelRatio,
    strength: sharedStrength,
    bands: sharedBands,
    luma: { value: f.luma },
    frame: { value: new THREE.Vector4(f.centre[0], f.centre[1], f.d, f.min_n) },
    slab: { value: new THREE.Vector2(f.slab[0], f.slab[1]) },
  };
}

/** Bind a hook's uniforms onto a shader being compiled. */
export function bindInsigniaUniforms(uniforms: Record<string, unknown>, h: InsigniaHook): void {
  uniforms.uInsSdf = h.sdf;
  uniforms.uInsColor = h.color;
  uniforms.uInsStrength = h.strength;
  uniforms.uInsLuma = h.luma;
  uniforms.uInsFrame = h.frame;
  uniforms.uInsSlab = h.slab;
  uniforms.uInsBands = h.bands;
  uniforms.uInsPixelRatio = h.pixelRatio;
}
