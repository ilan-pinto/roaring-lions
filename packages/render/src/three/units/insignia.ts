// The legacy (WebGL2) chunk. Spliced by `team-mask.ts`'s one hook, AFTER the team mark, inside the same `#ifdef USE_MAP`.

/** The varyings, for a material that carries the insignia but no team mark (the team head declares them otherwise). */
export const INSIGNIA_VARYINGS = /* glsl */ `varying vec3 vMarkPos;
varying vec3 vMarkNrm;`;

export const INSIGNIA_FRAGMENT_HEAD = /* glsl */ `uniform sampler2D uInsSdf;
uniform vec3 uInsColor;
uniform float uInsStrength;
uniform float uInsLuma;
uniform vec4 uInsFrame;
uniform vec2 uInsSlab;
uniform vec4 uInsBands;
uniform float uInsPixelRatio;
// Coverage of v in [lo, hi] at a given screen-space rate (the insignia's own: the team mark's rlMarkCov may be absent).
float rlInsCov( float v, float lo, float hi, float rate ) {
  float w = max( rate, ${INSIGNIA_MIN_RATE.toExponential()} );
  return clamp( ( v - lo ) / w + 0.5, 0.0, 1.0 ) * clamp( ( hi - v ) / w + 0.5, 0.0, 1.0 );
}
float rlInsEdge( float s, float rate ) {
  return clamp( ( s - ${INSIGNIA_SDF_EDGE} ) / max( rate, ${INSIGNIA_MIN_RATE.toExponential()} ) + 0.5, 0.0, 1.0 );
}`;

/**
 * The body. The sample and every derivative are taken unconditionally (no branch), so a quad straddling the box edge stays
 * defined, as the ground's road block requires.
 */
export const INSIGNIA_FRAGMENT = /* glsl */ `
{
  vec3 rlIP = vMarkPos;
  vec3 rlIN = normalize( vMarkNrm );
  vec2 rlIE = ( rlIP.xy - uInsFrame.xy ) / uInsFrame.z + 0.5;
  vec4 rlIS = texture2D( uInsSdf, ${INSIGNIA_ST_OFFSET} + ${INSIGNIA_ST_SCALE} * rlIE );
  vec2 rlIRE = vec2( fwidth( rlIE.x ), fwidth( rlIE.y ) );
  vec2 rlIRS = vec2( fwidth( rlIS.r ), fwidth( rlIS.g ) );
  float rlIRZ = fwidth( abs( rlIP.z ) );
  float rlInside = rlInsCov( abs( rlIP.z ), uInsSlab.x, uInsSlab.y, rlIRZ )
    * smoothstep( uInsFrame.w - ${INSIGNIA_NORMAL_SOFT}, uInsFrame.w + ${INSIGNIA_NORMAL_SOFT}, abs( rlIN.z ) )
    * rlInsCov( rlIE.x, 0.0, 1.0, rlIRE.x ) * rlInsCov( rlIE.y, 0.0, 1.0, rlIRE.y );
  float rlInsPx = 1.0 / max( max( rlIRE.x, rlIRE.y ), ${INSIGNIA_MIN_RATE.toExponential()} ) / uInsPixelRatio;
  float rlInsMask = uInsStrength * rlInside * smoothstep( uInsBands.x, uInsBands.y, rlInsPx ) * rlInsEdge( rlIS.r, rlIRS.x )
    * ( 1.0 - smoothstep( uInsBands.z, uInsBands.w, rlInsPx ) * rlInsEdge( rlIS.g, rlIRS.y ) );
  float rlInsY = dot( diffuseColor.rgb, vec3( ${INSIGNIA_LUMA_WEIGHTS.join(', ')} ) );
  // A stencil is PAINT: it keeps a third of the bake's grime, like the team mark's panel.
  vec3 rlInsPaint = min( uInsColor * mix( 1.0, rlInsY / uInsLuma, ${INSIGNIA_GRIME} ), vec3( 1.0 ) );
  diffuseColor.rgb = mix( diffuseColor.rgb, rlInsPaint, rlInsMask );
}`;

