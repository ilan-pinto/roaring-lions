/** A request body read under a byte bound, shared by the feedback ingest and the match routes.
 *  Moved out of `feedback-ingest.ts` unchanged. */
/** Reads at most `max` bytes; null if the body is longer. A lying or absent
 *  Content-Length cannot make this buffer more than `max` + one chunk. */
export async function readCapped(req: Request, max: number): Promise<Uint8Array<ArrayBuffer> | null> {
  if (!req.body) return new Uint8Array(0);
  const reader = req.body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > max) {
      await reader.cancel().catch(() => undefined);
      return null;
    }
    chunks.push(value);
  }
  const out = new Uint8Array(total);
  let at = 0;
  for (const c of chunks) {
    out.set(c, at);
    at += c.byteLength;
  }
  return out;
}
