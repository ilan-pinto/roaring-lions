"""Guards validate_audio.py's engine-loop check (GH-35).

Run: python3 tools/test_validate_audio_engines.py
Exits non-zero on failure. Dependency-free, like the ambience guard: every
case builds a manifest fragment over a scratch directory, and the decoder
(`measure`) is replaced by fixed readings, so neither ffmpeg nor anything under
assets/ is touched. Each case is one input the check must turn red on, beside
the passing one it was cut from.
"""
import copy
import importlib.util
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def load():
    spec = importlib.util.spec_from_file_location("validate_audio", os.path.join(HERE, "validate_audio.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# A moving loop as shipped: -24 LUFS file at gain 0.22 under master 0.9 is
# heard at -38.1 LUFS.
GOOD = {"channels": 1, "seconds": 8.011, "integrated": -24.0, "true_peak": -8.0, "seam_level_db": 0.5, "seam_gap_db": 2.0}
UNITS = {"mbt_lavi", "heli_peten", "jeep_shoded"}


def candidate(loop, v):
    return {
        "file": f"engines/{loop}_{v}.ogg", "alt": f"engines/{loop}_{v}.m4a", "loop_s": 8.011, "channels": 1,
        "license": "CC0-1.0", "source": "generated by docs/polish/audio/engines/engine_candidates.py",
    }


def engines(**over):
    loops = {name: {"gain": 0.22, "pick": "a", "a": candidate(name, "a"), "b": candidate(name, "b")}
             for name in ("tracked_move", "track_clank", "rotor")}
    e = {
        "radius_tiles": 14, "voice_cap": 4, "hysteresis_tiles": 2, "loops": loops,
        "families": {"tracked": {"move": "tracked_move", "clank": "track_clank"}, "rotor": {"rotor": "rotor"}},
        "by_type": {"mbt_lavi": "tracked", "heli_peten": "rotor", "jeep_shoded": "none"},
    }
    e.update(over)
    return e


def main():
    mod = load()
    bad = []

    def check(label, failures, want):
        ok = (not failures) if want is None else any(want in f for f in failures)
        print(f"{'ok  ' if ok else 'FAIL'} {label}" + ("" if ok else f" -- got {failures}"))
        if not ok:
            bad.append(label)

    def run(eng, reading=GOOD, master=0.9):
        """(failures, notes, declared). `reading` is what every file decodes
        to; None stands for no ffmpeg on PATH."""
        with tempfile.TemporaryDirectory() as d:
            os.makedirs(os.path.join(d, "engines"))
            for loop in ("tracked_move", "track_clank", "rotor"):
                for v in ("a", "b"):
                    for ext in ("ogg", "m4a"):
                        with open(os.path.join(d, "engines", f"{loop}_{v}.{ext}"), "wb") as fh:
                            fh.write(b"OggS")
            failures, notes = [], []
            man = {"master_gain": master, "engines": eng}
            declared = mod.check_engines(man, failures, notes, audio_dir=d, measure=lambda _p: reading, unit_ids=UNITS)
            return failures, notes, declared

    f, n, declared = run(engines())
    check("the shipped shape passes", f, None)
    ok = len(declared) == 12 and "engines/rotor_b.m4a" in declared
    print(f"{'ok  ' if ok else 'FAIL'} both encodings of both candidates are declared for the undeclared-file sweep")
    if not ok:
        bad.append("declared")
    ok = any("heard -38.1 LUFS" in x for x in n)
    print(f"{'ok  ' if ok else 'FAIL'} the heard level is file + gain + master")
    if not ok:
        bad.append("heard arithmetic")

    failures = []
    none_declared = mod.check_engines({"master_gain": 0.9}, failures, [], unit_ids=UNITS)
    check("no engines section at all is legal and declares nothing", failures + [f"{x}" for x in none_declared], None)
    e = engines()
    del e["loops"]["rotor"]["b"]
    check("a loop missing its b candidate fails", run(e)[0], "candidate b: not declared")
    e = engines()
    e["loops"]["rotor"]["pick"] = "c"
    check("a pick that is not a or b fails", run(e)[0], "pick 'c'")
    e = engines()
    e["loops"]["rotor"]["gain"] = 1.4
    check("a gain over 1 fails", run(e)[0], "gain 1.4 outside")
    e = engines()
    e["loops"]["rotor"]["a"]["license"] = "royalty-free"
    check("a non-CC licence fails", run(e)[0], "not redistribution-safe")
    e = engines()
    e["loops"]["rotor"]["a"]["alt"] = "engines/gone.m4a"
    check("a missing encoding fails", run(e)[0], "missing from assets/audio/")
    e = engines()
    e["loops"]["rotor"]["a"]["channels"] = 2
    check("a stereo engine fails (a placed sound is mono)", run(e)[0], "channels 2")
    check("a voice cap of 0 fails", run(engines(voice_cap=0))[0], "voice_cap 0")
    check("a fractional voice cap fails", run(engines(voice_cap=3.5))[0], "voice_cap 3.5")
    check("a radius past a one-shot's 26 tiles fails", run(engines(radius_tiles=40))[0], "radius_tiles 40")
    e = engines()
    e["families"]["rotor"]["clank"] = "track_clank"
    check("a clank outside the tracked family fails", run(e)[0], "only the tracked family carries a track clank")
    e = engines()
    e["families"]["tracked"]["idle"] = "tracked_idle"
    check("a layer naming an undeclared loop fails", run(e)[0], "names loop 'tracked_idle'")
    e = engines()
    e["families"]["tracked"]["horn"] = "tracked_move"
    check("an unknown layer fails", run(e)[0], "unknown layer 'horn'")
    e = engines()
    e["by_type"]["mbt_lavii"] = "tracked"
    check("a by_type id that is no shipped unit fails", run(e)[0], "'mbt_lavii' is not a shipped unit id")
    e = engines()
    e["by_type"]["mbt_lavi"] = "tracks"
    check("a by_type family that is not declared fails", run(e)[0], "names family 'tracks'")

    check("AAC priming left in (23 ms long) fails", run(engines(), dict(GOOD, seconds=8.034))[0], "priming or padding")
    check("a peak over -6 dBTP fails", run(engines(), dict(GOOD, true_peak=-5.6))[0], "over the engine ceiling -6.0 dBTP")
    check("a loop heard over -36 LUFS fails", run(engines(), dict(GOOD, integrated=-21.0))[0], "over the engine ceiling -36.0")
    check("a quiet loop is fine (a ceiling, not a band)", run(engines(), dict(GOOD, integrated=-34.0))[0], None)
    check("a 3 dB step at the seam fails", run(engines(), dict(GOOD, seam_level_db=3.0))[0], "seam steps 3.0 dB")
    check("a gap at the seam fails", run(engines(), dict(GOOD, seam_gap_db=-20.0))[0], "a gap at the loop's seam")

    f, n, _ = run(engines(), None)
    check("no ffmpeg is a named skip, not a pass or a failure", f, None)
    ok = any("engine loop NOT measured" in x for x in n)
    print(f"{'ok  ' if ok else 'FAIL'} the skip is named in the notes")
    if not ok:
        bad.append("skip named")

    # A commercial build strips an unconfirmed candidate, like any variant.
    man = {"engines": engines()}
    man["engines"]["loops"]["rotor"]["b"]["source"] = "a vendor; licence not yet confirmed"
    failures = []
    mod.check_commercial(man, failures)
    check("the commercial gate sees an engine candidate", failures, "licence not confirmed")
    stripped, excluded = mod.commercial_manifest(copy.deepcopy(man))
    ok = "b" not in stripped["engines"]["loops"]["rotor"] and "engines/rotor_b.ogg" in excluded
    print(f"{'ok  ' if ok else 'FAIL'} the commercial manifest leaves it out")
    if not ok:
        bad.append("commercial strip")

    if bad:
        print(f"\n{len(bad)} engine case(s) failed", file=sys.stderr)
        return 1
    print("validate_audio engines: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
