"""Save the source session of a KDF carrier's SHIPPED host as `art/src/vehicles/<id>_host.blend` (GH-943 batch 3).

    /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup \
        --python tools/vehicles/save_carrier_blend.py -- ifv_namer apc_eitan apc_kipod

`ifv_namer`, `apc_eitan` and `apc_kipod` have no re-runnable Blender export: the Namer's Meshy source is not in the tree,
and the Eitan and Kipod went through `rws-swap.ts` after theirs. The team-mark pass (`peel-host.ts`, `mark-pass.ts`)
therefore works on the shipped GLB's own bytes, and this script records those bytes as a .blend so the GLB has a source
under `art/src/vehicles/`: the SHIPPED `art/meshes/vehicles/<id>.glb` imported, its `kit_*` upgrade nodes and the
`death_root` wreck twins removed (both are regenerated by `pnpm kit:meshes` / `pnpm wreck:meshes`). What is left is the
live hull, tyres or tracks, and the remote weapon station on `turret_pivot`, in the vehicle's own frame, with the
bake as its one material. It is a snapshot, not an authoring file: edit the geometry here and the mark boxes, the
kit sources and the running-gear tags no longer describe it.

Meshy-generated geometry and bake (AI-generated, disclosed per CONTRIBUTING.md; ids in `docs/ASSET_PROVENANCE.md`).
No Meshy call is made. Existing `art/src/vehicles/apc_kipod.blend` and `eitan_apc.blend` are the superseded kit builds
and are left alone, hence the `_host` suffix.
"""
import os
import sys

import bpy

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def save(vid):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=os.path.join(REPO, "art", "meshes", "vehicles", f"{vid}.glb"))
    doomed = [o for o in bpy.data.objects if o.name.startswith(("kit_", "WRECK_", "death_root"))]
    for o in doomed:
        bpy.data.objects.remove(o, do_unlink=True)
    for act in list(bpy.data.actions):
        bpy.data.actions.remove(act)
    keep = sorted(o.name for o in bpy.data.objects)
    out = os.path.join(REPO, "art", "src", "vehicles", f"{vid}_host.blend")
    bpy.ops.wm.save_as_mainfile(filepath=out, compress=True)
    print(f"BLEND_OK {vid}: {len(doomed)} node(s) removed, kept {keep} -> {out}")


for vid in sys.argv[sys.argv.index("--") + 1:]:
    save(vid)
