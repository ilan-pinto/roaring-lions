#!/usr/bin/env python3
"""
Roaring Lions -- encode the GH-35 engine loops for the game.

    python3 tools/encode_engine_loops.py [-h | --help]

The twelve engine candidates (an A and a B of six loops) are generated by
docs/polish/audio/engines/engine_candidates.py, which writes 16-bit mono WAVs
beside itself for the lead's listening page. The game does not ship WAVs: like
every other clip here it ships OGG Vorbis (everyone) plus AAC in M4A (Safari).
This script encodes those WAVs into assets/audio/engines/ with gen_audio.py's
own clip codecs and rewrites the generator's facts -- `file`, `alt`, `loop_s`,
`channels`, `license`, `source` -- into data/audio.json's `engines.loops`. A
loop's `gain` and `pick` are the mix's and the lead's, and are left alone.

Both candidates of every loop ship, so the lead can judge A against B in the
game itself (`&engines=a|b` in the sandbox); the one he picks is a one-line
change to that loop's `pick`. The other can be deleted then.

CC0 by construction: the candidates are synthesised from noise, envelopes and
sines (see the generator's own header). Nothing third-party is in them.

Regenerate the WAVs first (`python3 docs/polish/audio/engines/engine_candidates.py`)
if the generator changed; this script never synthesises anything itself.
"""
import json
import os
import subprocess
import sys
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CANDIDATES = os.path.join(ROOT, "docs", "polish", "audio", "engines")
OUT = os.path.join(ROOT, "assets", "audio")
MANIFEST = os.path.join(ROOT, "data", "audio.json")

# loop id (the key in data/audio.json's `engines.loops`) -> {variant: WAV stem
# under docs/polish/audio/engines/}.
LOOPS = {
    "tracked_idle": {"a": "tracked_idle_a_v12", "b": "tracked_idle_b_lumpy"},
    "tracked_move": {"a": "tracked_move_a_pulling", "b": "tracked_move_b_low_gear"},
    "track_clank": {"a": "track_clank_a_sprocket", "b": "track_clank_b_slack"},
    "wheeled_idle": {"a": "wheeled_idle_a_petrol", "b": "wheeled_idle_b_diesel"},
    "wheeled_move": {"a": "wheeled_move_a_cruise", "b": "wheeled_move_b_gravel"},
    "rotor": {"a": "rotor/rotor_a_blade_slap", "b": "rotor/rotor_b_overhead"},
}

# gen_audio.py's CLIP_CODECS for the OGG: an engine is heard close, so it gets
# a battle clip's quality rather than an ambience bed's. The M4A (Safari) is
# 160 kb/s, not the clips' 96: at 96 and 128 ffmpeg's AAC encoder overshot
# rotor A's blade slaps from -8.0 to -5.6 dBTP, over validate:audio's -6
# ceiling; at 160 it reads -8.1. One rate for all twelve, not a per-file one.
CODECS = {".ogg": ["-c:a", "libvorbis", "-q:a", "3"], ".m4a": ["-c:a", "aac", "-b:a", "160k"]}
SOURCE = (
    "generated by docs/polish/audio/engines/engine_candidates.py (GH-35 candidate, PR #597), "
    "encoded by tools/encode_engine_loops.py"
)

USAGE = """usage: python3 tools/encode_engine_loops.py [-h | --help]

Encodes the twelve engine-candidate WAVs in docs/polish/audio/engines/ into
assets/audio/engines/ (OGG + M4A) and rewrites their facts in data/audio.json.
"""


def wav_facts(path):
    """(frames, rate, channels) of a WAV, read from its header."""
    with wave.open(path, "rb") as w:
        return w.getnframes(), w.getframerate(), w.getnchannels()


def main(argv):
    if argv:
        if any(a in ("-h", "--help") for a in argv):
            print(USAGE, end="")
            return 0
        print(f"unknown argument(s): {' '.join(argv)}\n\n{USAGE}", end="", file=sys.stderr)
        return 2
    os.makedirs(os.path.join(OUT, "engines"), exist_ok=True)
    with open(MANIFEST) as fh:
        man = json.load(fh)
    loops = man.setdefault("engines", {}).setdefault("loops", {})
    for loop, variants in LOOPS.items():
        entry = loops.setdefault(loop, {})
        for variant, stem in variants.items():
            wav = os.path.join(CANDIDATES, stem + ".wav")
            if not os.path.exists(wav):
                print(f"missing {os.path.relpath(wav, ROOT)} -- run engine_candidates.py first", file=sys.stderr)
                return 1
            frames, rate, channels = wav_facts(wav)
            base = os.path.join(OUT, "engines", f"{loop}_{variant}")
            for ext, args in CODECS.items():
                subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", wav, *args, base + ext], check=True)
            facts = {
                "file": os.path.relpath(base + ".ogg", OUT),
                "alt": os.path.relpath(base + ".m4a", OUT),
                "candidate": os.path.basename(stem),
                "loop_s": round(frames / rate, 6),
                "channels": channels,
                "license": "CC0-1.0",
                "source": SOURCE,
            }
            entry.setdefault(variant, {}).update(facts)
            print(f"  {loop} {variant}: {os.path.basename(stem)} -> engines/{loop}_{variant}.ogg + .m4a")
    with open(MANIFEST, "w") as fh:
        json.dump(man, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print("\nupdated data/audio.json engines.loops")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
