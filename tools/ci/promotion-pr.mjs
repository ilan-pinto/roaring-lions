// B5-1: the weekly promotion PR, dev -> main (lead, 17 Nov 2026).
//
// PRs merge into `dev`; `main` is production and moves only through ONE promotion PR that the lead approves and merges
// with a MERGE commit. `.github/workflows/promotion-pr.yml` runs this weekly (and on dispatch) to open that PR, or bring
// its body up to date. It never merges, and it changes nothing when the open PR already says what this would write.
//
//   node tools/ci/promotion-pr.mjs --base=origin/main --head=origin/dev [--ci=<json>] [--open=<json>] [--repo=owner/name]
//                                  [--server=https://github.com] --out=<body file>
//
//   --ci     {"tip": <workflow run or null>, "latest": <workflow run or null>}: the `ci` run on the dev tip's sha, and the
//            newest `ci` push run on dev (either may be null). Missing file or flag: the body says the result is unknown.
//   --open   the JSON array `gh pr list --base main --head dev --state open --json number,title,body` printed.
//
// Prints GITHUB_OUTPUT lines on stdout: `action=` create | update | none | empty | foreign, `number=` (update/none/
// foreign) and `title=`. stderr carries the human summary.
//
// The pure half (everything exported) is tested on literal fixtures in tools/src/ci/promotion-pr.test.ts; only `main`
// touches git and the filesystem.
//
// Why "PR NNN" and never a hash: the squash subjects carry "(PR 1547)" or GitHub's "(#1544)", and the UI palette gate
// reads a hash and digits as a colour (CLAUDE.md, house rules), so the body is written without one anywhere.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

/** The hidden line that marks a PR as this workflow's. A dev -> main PR without it was opened by hand and is left alone. */
export const MARKER = '<!-- promotion-pr: generated by .github/workflows/promotion-pr.yml; edit the PR, not this line -->';

/**
 * The last line this workflow writes. Anything after it belongs to someone else (a review bot appends its summary to a
 * PR body, as one did on the hand-opened promotion PR 1553): it is ignored when judging "already current", and kept
 * when the body is updated.
 */
export const END = '<!-- promotion-pr: end -->';

/** GitHub refuses a PR body over 65,536 characters; stay well under it. */
export const BODY_LIMIT = 60000;

/** The group a subject with no recognisable prefix lands in. */
export const OTHER_GROUP = 'other';

// A trailing PR reference: "(PR 1547)" or "(#1544)", optionally followed by spaces.
const TRAILING_REF = /\s*\((?:PR\s+|#)(\d+)\)\s*$/;
// GitHub's own merge-commit subject for a PR merged without squashing.
const MERGE_PR = /^Merge pull request #(\d+) from \S+/;
// A prefix is the text before the first colon, if it looks like one: short, starting with a letter, and made only of
// what this history's prefixes use ("app", "docs(campaign)", "fix(ui)!", "ci + CLAUDE.md", "tools, economy, net").
const PREFIX = /^([A-Za-z][\w.+ ,()/!-]{0,39}):\s/;

/**
 * Rewrites every hash-and-digits reference as the house form, and keeps an @handle from notifying anyone.
 *
 * A trailing "(#NNN)" is a PR (GitHub writes it on a squash) and becomes "(PR NNN)"; any other "#NNN" is an issue or a PR
 * and becomes "GH-NNN", the house spelling for both. "@name" is wrapped in backticks: GitHub notifies a bare @name in a
 * PR body, and a subject such as "bump @types/node" must not ping a user called "types".
 *
 * @param {string} text
 * @returns {string}
 */
export function neutralise(text) {
  return text
    .replace(/\((?:PR\s+|#)(\d+)\)\s*$/, '(PR $1)')
    .replace(/#(\d+)/g, 'GH-$1')
    .replace(/(^|[^\w`])@([A-Za-z0-9][\w./-]*)/g, '$1`@$2`');
}

/**
 * The changelog group of a subject: the first word of its prefix, lowercased ("ci + CLAUDE.md" -> "ci",
 * "docs(campaign)" -> "docs", "fix(ui)" -> "fix"), or OTHER_GROUP when it has none.
 *
 * @param {string} subject
 * @returns {string}
 */
export function groupOf(subject) {
  const m = PREFIX.exec(subject);
  if (!m) return OTHER_GROUP;
  const word = /^[A-Za-z][\w-]*/.exec(m[1]);
  return word ? word[0].toLowerCase() : OTHER_GROUP;
}

/**
 * @typedef {{ sha: string, parents: string[], subject: string, body: string }} Commit
 * @typedef {{ pr: number | null, sha: string, group: string, line: string }} Entry
 */

/**
 * One changelog entry for a first-parent commit of dev, or null for one that is not a change (a merge of main back into
 * dev, or main's own release bump).
 *
 * - a squash commit "subject (PR NNN)" / "subject (#NNN)": that PR, the subject as its line;
 * - GitHub's "Merge pull request #NNN from owner/branch": that PR, the first line of the commit body (the PR title);
 * - any other merge commit: null (it brings in nothing that is not listed on its own);
 * - "chore(release): v..." : null (the version job writes those on main; one on dev would be a mistake, not a change);
 * - anything else: a direct commit, listed by its short sha.
 *
 * @param {Commit} commit
 * @returns {Entry | null}
 */
export function entryOf(commit) {
  const sha = commit.sha.slice(0, 9);
  const merge = MERGE_PR.exec(commit.subject);
  if (merge) {
    const title = commit.body.split('\n').map((l) => l.trim()).find((l) => l.length > 0) ?? commit.subject;
    const clean = title.replace(TRAILING_REF, '');
    return { pr: Number(merge[1]), sha, group: groupOf(clean), line: neutralise(`${clean} (PR ${merge[1]})`) };
  }
  if (commit.parents.length > 1) return null;
  if (/^chore\(release\): v/.test(commit.subject)) return null;
  const ref = TRAILING_REF.exec(commit.subject);
  if (ref) return { pr: Number(ref[1]), sha, group: groupOf(commit.subject), line: neutralise(commit.subject) };
  return { pr: null, sha, group: groupOf(commit.subject), line: neutralise(commit.subject) };
}

/**
 * The entries for a `git log --first-parent base..head` listing (newest first, as git prints it), oldest first, one
 * per PR: a PR number seen twice (a revert-and-reland keeps its own new number; a cherry-pick does not) is kept once.
 *
 * @param {readonly Commit[]} commits
 * @returns {Entry[]}
 */
export function entriesOf(commits) {
  const seen = new Set();
  const out = [];
  for (const c of [...commits].reverse()) {
    const e = entryOf(c);
    if (!e) continue;
    if (e.pr !== null) {
      if (seen.has(e.pr)) continue;
      seen.add(e.pr);
    }
    out.push(e);
  }
  return out;
}

/**
 * @typedef {{ id?: number, status?: string | null, conclusion?: string | null, html_url?: string, head_sha?: string }} Run
 */

/**
 * The "latest dev CI" line. `tip` is the `ci` run on dev's tip sha; `latest` the newest `ci` push run on dev.
 *
 * @param {string} headSha
 * @param {{ tip?: Run | null, latest?: Run | null } | null} ci
 * @returns {string}
 */
export function ciLine(headSha, ci) {
  const short = headSha.slice(0, 9);
  const verdict = (/** @type {Run} */ r) =>
    r.status === 'completed' ? `**${r.conclusion ?? 'no conclusion'}**` : `**${r.status ?? 'unknown'}** (not finished)`;
  if (ci && ci.tip) {
    return `**Latest dev CI:** ${verdict(ci.tip)} on \`${short}\`, the dev tip: ${ci.tip.html_url ?? '(no run link)'}`;
  }
  if (ci && ci.latest) {
    const at = (ci.latest.head_sha ?? '').slice(0, 9) || 'an unknown sha';
    return (
      `**Latest dev CI:** no \`ci\` run found for the dev tip \`${short}\`. The newest \`ci\` run on dev is ` +
      `${verdict(ci.latest)} on \`${at}\`: ${ci.latest.html_url ?? '(no run link)'}`
    );
  }
  return `**Latest dev CI:** unknown. No \`ci\` push run on dev was found for \`${short}\` or before it.`;
}

/**
 * The PR title. It depends only on the content, never on a date, so an unchanged dev writes an unchanged title.
 *
 * @param {readonly Entry[]} entries
 * @returns {string}
 */
export function titleOf(entries) {
  const prs = entries.filter((e) => e.pr !== null).length;
  const direct = entries.length - prs;
  const parts = [`${prs} PR${prs === 1 ? '' : 's'}`];
  if (direct > 0) parts.push(`${direct} direct commit${direct === 1 ? '' : 's'}`);
  return `promote: dev to main (${parts.join(', ')})`;
}

/**
 * The PR body. Deterministic in its inputs (no clock), which is what lets "already current" be a string comparison.
 *
 * @param {{ entries: readonly Entry[], headSha: string, baseSha: string, ci: { tip?: Run | null, latest?: Run | null } | null,
 *           compareUrl?: string | null, limit?: number }} input
 * @returns {string}
 */
export function renderBody({ entries, headSha, baseSha, ci, compareUrl = null, limit = BODY_LIMIT }) {
  const prs = entries.filter((e) => e.pr !== null);
  const direct = entries.filter((e) => e.pr === null);

  const head = [
    '**Promotion: `dev` to `main`.** Opened and kept current by the weekly `promotion-pr` workflow, which never merges.',
    'Merge it with a **merge commit** (never squash or rebase) once the lead approves: Cloudflare deploys `main`.',
    '',
    `\`dev\` at \`${headSha.slice(0, 9)}\`, \`main\` at \`${baseSha.slice(0, 9)}\`: ${prs.length} PR${prs.length === 1 ? '' : 's'}` +
      (direct.length > 0 ? ` and ${direct.length} direct commit${direct.length === 1 ? '' : 's'}` : '') +
      (compareUrl ? `. Full diff: ${compareUrl}` : '.'),
    '',
    ciLine(headSha, ci),
    '',
    '**This PR has no `ci` run of its own.** A PR opened or edited with `GITHUB_TOKEN` starts no workflow (GitHub\'s guard',
    'against loops), so its checks stay empty or pending. The dev CI line above is the push run of the same tip. To get a',
    'run on the PR itself, a person closes and reopens it; the next merge into `dev` by a person also starts one.',
    '',
    '## Changelog',
    '',
  ];

  /** @type {Map<string, Entry[]>} */
  const groups = new Map();
  for (const e of prs) {
    const list = groups.get(e.group) ?? [];
    list.push(e);
    groups.set(e.group, list);
  }
  const names = [...groups.keys()].sort((a, b) =>
    a === OTHER_GROUP ? 1 : b === OTHER_GROUP ? -1 : a.localeCompare(b, 'en'),
  );

  /** @type {string[]} */
  const lines = [];
  for (const name of names) {
    const list = groups.get(name) ?? [];
    lines.push(`### ${name} (${list.length})`, '');
    for (const e of list) lines.push(`- ${e.line}`);
    lines.push('');
  }
  if (direct.length > 0) {
    lines.push(`### Direct commits, no PR (${direct.length})`, '');
    for (const e of direct) lines.push(`- \`${e.sha}\` ${e.line}`);
    lines.push('');
  }
  if (entries.length === 0) lines.push('Nothing on `dev` that `main` does not already have.', '');

  const tail = [MARKER, `<!-- promotion-pr: dev=${headSha} -->`, END];

  let body = [...head, ...lines, ...tail].join('\n');
  if (body.length > limit) {
    const fixed = [...head, ...tail].join('\n').length + 200;
    const kept = [];
    let size = 0;
    for (const l of lines) {
      if (fixed + size + l.length + 1 > limit) break;
      kept.push(l);
      size += l.length + 1;
    }
    const dropped = lines.length - kept.length;
    kept.push('', `(The changelog is cut here: ${dropped} more lines would pass GitHub's body limit. See the full diff.)`, '');
    body = [...head, ...kept, ...tail].join('\n');
  }
  if (/#[0-9]/.test(body)) throw new Error('promotion-pr: a hash followed by a digit survived into the body');
  return body;
}

/** Compares two bodies the way GitHub may hand one back: CRLF folded and trailing whitespace ignored. */
const norm = (/** @type {string} */ s) => s.replace(/\r\n/g, '\n').replace(/\s+$/, '');

/**
 * Splits an open PR's body at END: `ours` up to and including it, `tail` whatever another writer appended after it.
 * A body with no END is all ours.
 *
 * @param {string} body
 * @returns {{ ours: string, tail: string }}
 */
export function splitBody(body) {
  const at = body.lastIndexOf(END);
  if (at < 0) return { ours: body, tail: '' };
  const cut = at + END.length;
  return { ours: body.slice(0, cut), tail: body.slice(cut) };
}

/**
 * The body to send on an update: ours, then whatever another writer had appended after END on the open PR.
 *
 * @param {string} body ours, as renderBody wrote it
 * @param {string} previous the open PR's current body
 * @returns {string}
 */
export function withTail(body, previous) {
  const { tail } = splitBody(previous.replace(/\r\n/g, '\n'));
  return tail.trim() ? `${body}\n\n${tail.replace(/^\n+/, '').replace(/\s+$/, '')}` : body;
}

/**
 * What the workflow should do.
 *
 * - `empty`: dev holds nothing main lacks, so there is nothing to promote (an open PR, if any, is left alone);
 * - `create`: no open dev -> main PR;
 * - `none`: our open PR already carries exactly this title and body (anything appended after END aside);
 * - `update`: our open PR says something else;
 * - `foreign`: a dev -> main PR is open WITHOUT our marker, so a person opened it: never overwrite their text.
 *
 * With several open (it should not happen: GitHub refuses a second PR for the same head and base) the lowest number is
 * the one acted on.
 *
 * @param {{ entries: readonly Entry[], title: string, body: string,
 *           open: readonly { number: number, title?: string, body?: string | null }[] }} input
 * @returns {{ action: 'empty' | 'create' | 'none' | 'update' | 'foreign', number: number | null }}
 */
export function decide({ entries, title, body, open }) {
  const sorted = [...open].sort((a, b) => a.number - b.number);
  const first = sorted[0];
  if (entries.length === 0) return { action: 'empty', number: first ? first.number : null };
  if (!first) return { action: 'create', number: null };
  const theirs = first.body ?? '';
  if (!theirs.includes(MARKER)) return { action: 'foreign', number: first.number };
  if (norm(splitBody(theirs).ours) === norm(body) && (first.title ?? '') === title) return { action: 'none', number: first.number };
  return { action: 'update', number: first.number };
}

/**
 * Parses `git log --first-parent --format=%H%x1f%P%x1f%s%x1f%b%x1e` output.
 *
 * @param {string} raw
 * @returns {Commit[]}
 */
export function parseLog(raw) {
  return raw
    .split('\x1e')
    .map((r) => r.replace(/^\n+/, ''))
    .filter((r) => r.length > 0)
    .map((r) => {
      const [sha = '', parents = '', subject = '', body = ''] = r.split('\x1f');
      return { sha, parents: parents.split(' ').filter(Boolean), subject, body: body.trim() };
    });
}

/** @param {string[]} argv */
function main(argv) {
  /** @type {Record<string, string>} */
  const args = {};
  for (const a of argv) {
    const m = /^--([a-z-]+)=(.*)$/.exec(a);
    if (!m) throw new Error(`promotion-pr: unknown argument ${a}`);
    args[m[1]] = m[2];
  }
  const base = args.base ?? 'origin/main';
  const head = args.head ?? 'origin/dev';
  if (!args.out) throw new Error('promotion-pr: --out=<body file> is required');

  const git = (/** @type {string[]} */ ...a) => execFileSync('git', a, { encoding: 'utf8' });
  const headSha = git('rev-parse', head).trim();
  const baseSha = git('rev-parse', base).trim();
  const commits = parseLog(git('log', '--first-parent', '--format=%H%x1f%P%x1f%s%x1f%b%x1e', `${base}..${head}`));
  const entries = entriesOf(commits);

  const readJson = (/** @type {string | undefined} */ p) => (p && existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null);
  const ci = readJson(args.ci);
  const open = readJson(args.open) ?? [];
  const server = args.server ?? 'https://github.com';
  const compareUrl = args.repo ? `${server}/${args.repo}/compare/${baseSha.slice(0, 12)}...${headSha.slice(0, 12)}` : null;

  const title = titleOf(entries);
  const body = renderBody({ entries, headSha, baseSha, ci, compareUrl });
  const { action, number } = decide({ entries, title, body, open });
  // An update keeps what another writer appended after END; a create writes ours alone.
  const target = action === 'update' ? open.find((/** @type {{ number: number }} */ p) => p.number === number) : null;
  writeFileSync(args.out, `${withTail(body, target ? target.body ?? '' : '')}\n`);

  console.error(
    `promotion-pr: ${base}..${head} holds ${commits.length} first-parent commits, ${entries.length} entries; action ${action}` +
      (number !== null ? ` on PR ${number}` : ''),
  );
  process.stdout.write(`action=${action}\nnumber=${number ?? ''}\ntitle=${title}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
